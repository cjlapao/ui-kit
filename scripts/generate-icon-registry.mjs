#!/usr/bin/env node
/*
 * Rebuilds react/src/icons/registry.ts from the components directory.
 *
 * Drop a new SVG component at react/src/icons/components/Foo.tsx (exported as
 * `export const Foo`) and run this — the import list, the `IconName` union and
 * the registry map all come from the directory, so a manual edit can only ever
 * be wrong. The Icons page in the demo shows a live warning if the directory
 * has outgrown the registry; the vitest drift guard fails the suite.
 *
 *   node scripts/generate-icon-registry.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const componentsDir = path.join(root, "react/src/icons/components");
const outFile = path.join(root, "react/src/icons/registry.ts");

// The export name is the truth (a file's own `export const X`), the filename
// is only where to look for it — so a stray file whose name and export differ
// still lands under its real icon name.
const entries = fs
  .readdirSync(componentsDir)
  .filter((f) => f.endsWith(".tsx"))
  .map((f) => {
    const src = fs.readFileSync(path.join(componentsDir, f), "utf8");
    const m = src.match(/export const (\w+)/);
    if (!m) {
      console.error(`No export const found in components/${f} — skipping.`);
      return null;
    }
    return { name: m[1], file: f.replace(/\.tsx$/, "") };
  })
  .filter(Boolean)
  .sort((a, b) => (a.name < b.name ? -1 : 1));

const dupe = new Set();
for (const e of entries) {
  if (dupe.has(e.name)) {
    console.error(`Duplicate icon name "${e.name}" — fix the files.`);
    process.exit(1);
  }
  dupe.add(e.name);
}

const lines = [];
lines.push('import React from "react";');
for (const e of entries) lines.push(`import { ${e.name} } from "./components/${e.file}";`);
lines.push("");
lines.push("// GENERATED by scripts/generate-icon-registry.mjs — do not edit by");
lines.push("// hand. The components directory is the source of truth; running the");
lines.push("// generator rewrites this whole file. A vitest guard fails the suite");
lines.push("// when the directory gains or loses a component without a regen.");
lines.push("export type IconName =");
for (const e of entries) lines.push(`  | "${e.name}"`);
lines.push("  | (string & {});");
lines.push("");
lines.push(
  "export const iconRegistry: Record<",
);
lines.push("  IconName,");
lines.push(
  "  React.ForwardRefExoticComponent<React.SVGProps<SVGSVGElement>>",
);
lines.push("> = {");
for (const e of entries) lines.push(`  ${e.name}: ${e.name},`);
lines.push("};");
lines.push("");

fs.writeFileSync(outFile, lines.join("\n"));
console.log(`Wrote ${outFile} (${entries.length} icons)`);
