import type { SurfaceVariant } from "./Theme";

export const SURFACE_TRANSPARENCIES = ["none", "low", "medium", "high"] as const;
export type SurfaceTransparency = (typeof SURFACE_TRANSPARENCIES)[number];

/** The existing alpha is the upper bound; only these surfaces opt in by default. */
export function resolveSurfaceTransparency(variant: SurfaceVariant, value?: SurfaceTransparency): SurfaceTransparency {
  return value ?? (variant === "glass" || variant === "liquid-glass" || variant === "subtle" ? "high" : "none");
}

/**
 * Change only background alpha, never content, borders, shadows or decorations.
 * Opaque fills precompose the existing tint on white / neutral-900, preserving
 * its appearance without allowing the application's backdrop to bleed through.
 * The CSS variable utilities below are generated by generate-safelist.mjs.
 */
export function getSurfaceTransparencyClasses(classes: string, variant: SurfaceVariant, transparency?: SurfaceTransparency): string {
  const level = resolveSurfaceTransparency(variant, transparency);
  if (level === "high") return classes;
  const tokens = classes.split(/\s+/).filter(Boolean);
  const background = /^((?:(?:dark|hover):)*)bg-((?:[a-z]+-\d+)|white|black)(?:\/(\d+))?$/;
  // A surface that was already opaque must never become more transparent.
  if (!tokens.some(token => background.test(token) && token.includes("/"))) return classes;
  const converted = tokens.map(token => {
    const match = token.match(background);
    if (!match) return token;
    const [, prefix, colour, alpha = "100"] = match;
    return `${prefix}[--ui-surface-color:var(--color-${colour})] ${prefix}[--ui-surface-alpha:${Math.min(100, Number(alpha))}%]`;
  });
  return [
    ...converted,
    "ui-surface-fill",
    `ui-surface-transparency-${level}`,
    "[--ui-surface-base:var(--color-white)] dark:[--ui-surface-base:var(--color-neutral-900)]",
  ].join(" ");
}
